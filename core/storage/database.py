"""
core/storage/database.py  --  Database Persistence for the DQ Pipeline
======================================================================
Handles:
  - Creating the schema (batch_runs, issues, quality_scores tables)
  - Writing pipeline results to PostgreSQL or SQLite
  - Querying historical batches and trends

Requires: sqlalchemy (pip install sqlalchemy psycopg2-binary)
For SQLite (local dev): no extra dependencies needed.
"""

import json
import logging
import os
from datetime import datetime, timezone
from typing import Dict, Any, Optional, List

import pandas as pd

logger = logging.getLogger("dq_engine.db")

# ---------------------------------------------------------------------------
# Shared engine cache (one connection pool per process)
# ---------------------------------------------------------------------------
_ENGINE_CACHE = {}


def get_engine(config: Dict[str, Any] = None):
    """
    Get a SQLAlchemy engine. Priority order:
    1. DATABASE_URL environment variable (used in ECS/production)
    2. Config dict (used when called from pipeline)
    3. Default SQLite fallback
    """
    from sqlalchemy import create_engine

    # 1. DATABASE_URL env var takes priority (set in ECS task definition)
    db_url = os.environ.get("DATABASE_URL")
    if db_url:
        cache_key = db_url
        if cache_key not in _ENGINE_CACHE:
            logger.info("Using DATABASE_URL from environment")
            _ENGINE_CACHE[cache_key] = create_engine(
                db_url,
                pool_size=5,
                max_overflow=10,
                pool_pre_ping=True,  # reconnect on stale connections
            )
        return _ENGINE_CACHE[cache_key]

    # 2. Config dict
    if config:
        return _get_engine(config)

    # 3. SQLite fallback
    os.makedirs("./output", exist_ok=True)
    url = "sqlite:///./output/dq_investigator.db"
    if url not in _ENGINE_CACHE:
        _ENGINE_CACHE[url] = create_engine(url)
    return _ENGINE_CACHE[url]

# ---------------------------------------------------------------------------
# Schema DDL — executed on first run or via migrate command
# ---------------------------------------------------------------------------
SCHEMA_SQL = """
-- Batch runs: one row per pipeline execution
CREATE TABLE IF NOT EXISTS batch_runs (
    batch_id        TEXT PRIMARY KEY,
    timestamp       TIMESTAMP NOT NULL,
    source_file     TEXT,
    rows_processed  INTEGER NOT NULL,
    columns         TEXT,                -- JSON array of column names
    overall_score   REAL NOT NULL,
    pass            BOOLEAN NOT NULL,
    pass_threshold  REAL NOT NULL,
    issues_count    INTEGER NOT NULL,
    llm_calls       INTEGER DEFAULT 0,
    data_sent_to_llm BOOLEAN DEFAULT FALSE,
    completeness    REAL,
    uniqueness      REAL,
    consistency     REAL,
    validity        REAL,
    accuracy        REAL,
    timeliness      REAL,
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Issues: one row per detected issue
CREATE TABLE IF NOT EXISTS issues (
    id              INTEGER PRIMARY KEY AUTOINCREMENT,
    batch_id        TEXT NOT NULL REFERENCES batch_runs(batch_id),
    row_id          INTEGER,
    column_name     TEXT,
    issue_type      TEXT,
    detail          TEXT,
    severity        TEXT,
    value           TEXT,
    expected        TEXT,
    rule            TEXT,
    suggestion      TEXT,
    description     TEXT,
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Audit trail: one row per pipeline step
CREATE TABLE IF NOT EXISTS audit_trail (
    id              INTEGER PRIMARY KEY AUTOINCREMENT,
    batch_id        TEXT NOT NULL REFERENCES batch_runs(batch_id),
    step_name       TEXT NOT NULL,
    duration_ms     INTEGER,
    details         TEXT,                -- JSON blob for step-specific data
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Index for fast batch lookups
CREATE INDEX IF NOT EXISTS idx_issues_batch ON issues(batch_id);
CREATE INDEX IF NOT EXISTS idx_audit_batch ON audit_trail(batch_id);
CREATE INDEX IF NOT EXISTS idx_batch_timestamp ON batch_runs(timestamp);

-- AI Enrichment: smart rules generated by AI
CREATE TABLE IF NOT EXISTS ai_smart_rules (
    id              INTEGER PRIMARY KEY AUTOINCREMENT,
    batch_id        TEXT NOT NULL REFERENCES batch_runs(batch_id),
    column_name     TEXT,
    rule_type       TEXT,
    description     TEXT,
    condition_text  TEXT,
    confidence      REAL,
    reasoning       TEXT,
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- AI Enrichment: cross-column issues
CREATE TABLE IF NOT EXISTS ai_cross_column (
    id              INTEGER PRIMARY KEY AUTOINCREMENT,
    batch_id        TEXT NOT NULL REFERENCES batch_runs(batch_id),
    columns_involved TEXT,               -- JSON array of column names
    check_type      TEXT,
    description     TEXT,
    severity        TEXT,
    suggested_query TEXT,
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- AI Enrichment: anomaly explanations
CREATE TABLE IF NOT EXISTS ai_explanations (
    id              INTEGER PRIMARY KEY AUTOINCREMENT,
    batch_id        TEXT NOT NULL REFERENCES batch_runs(batch_id),
    column_name     TEXT,
    issue_type      TEXT,
    explanation     TEXT,
    business_impact TEXT,
    suggested_action TEXT,
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- AI Enrichment: issue triage (priority-ranked)
CREATE TABLE IF NOT EXISTS ai_triage (
    id              INTEGER PRIMARY KEY AUTOINCREMENT,
    batch_id        TEXT NOT NULL REFERENCES batch_runs(batch_id),
    priority        INTEGER,
    column_name     TEXT,
    issue_type      TEXT,
    issue_count     INTEGER,
    severity        TEXT,
    reason          TEXT,
    effort          TEXT,
    recommendation  TEXT,
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- AI Enrichment: executive summary
CREATE TABLE IF NOT EXISTS ai_executive_summary (
    id              INTEGER PRIMARY KEY AUTOINCREMENT,
    batch_id        TEXT NOT NULL REFERENCES batch_runs(batch_id),
    summary_text    TEXT NOT NULL,
    provider        TEXT,
    total_time_secs REAL,
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_ai_smart_rules_batch ON ai_smart_rules(batch_id);
CREATE INDEX IF NOT EXISTS idx_ai_cross_column_batch ON ai_cross_column(batch_id);
CREATE INDEX IF NOT EXISTS idx_ai_explanations_batch ON ai_explanations(batch_id);
CREATE INDEX IF NOT EXISTS idx_ai_triage_batch ON ai_triage(batch_id);
CREATE INDEX IF NOT EXISTS idx_ai_exec_summary_batch ON ai_executive_summary(batch_id);
"""

# PostgreSQL version (uses SERIAL instead of AUTOINCREMENT)
SCHEMA_SQL_PG = SCHEMA_SQL.replace(
    "INTEGER PRIMARY KEY AUTOINCREMENT",
    "SERIAL PRIMARY KEY"
)


# ---------------------------------------------------------------------------
# Connection management
# ---------------------------------------------------------------------------
def _get_engine(config: Dict[str, Any]):
    """Create a SQLAlchemy engine from config dict."""
    from sqlalchemy import create_engine

    db_cfg = config.get("output", {}).get("database", {})
    engine_type = db_cfg.get("engine", "sqlite")

    if engine_type == "sqlite":
        db_path = db_cfg.get("path", "./output/dq_investigator.db")
        os.makedirs(os.path.dirname(os.path.abspath(db_path)), exist_ok=True)
        url = f"sqlite:///{db_path}"
        logger.info(f"Using SQLite: {db_path}")
    elif engine_type == "postgresql":
        host = db_cfg.get("host", "localhost")
        port = db_cfg.get("port", 5432)
        name = db_cfg.get("name", "dq_investigator")
        user = db_cfg.get("user", "")
        password = db_cfg.get("password", "")
        url = f"postgresql://{user}:{password}@{host}:{port}/{name}"
        logger.info(f"Using PostgreSQL: {host}:{port}/{name}")
    else:
        raise ValueError(f"Unsupported database engine: {engine_type}")

    if url not in _ENGINE_CACHE:
        kwargs = {"pool_pre_ping": True} if engine_type == "postgresql" else {}
        _ENGINE_CACHE[url] = create_engine(url, **kwargs)
    return _ENGINE_CACHE[url]


# ---------------------------------------------------------------------------
# Schema creation
# ---------------------------------------------------------------------------
def init_schema(config: Dict[str, Any]) -> None:
    """Create tables if they don't exist."""
    engine = _get_engine(config)
    db_type = config.get("output", {}).get("database", {}).get("engine", "sqlite")

    sql = SCHEMA_SQL_PG if db_type == "postgresql" else SCHEMA_SQL

    with engine.connect() as conn:
        for statement in sql.split(";"):
            stmt = statement.strip()
            if stmt:
                conn.execute(conn.connection.cursor().execute(stmt) if False else __import__("sqlalchemy").text(stmt))
        conn.commit()

    logger.info("Database schema initialized")


def _init_schema_safe(engine, db_type: str) -> None:
    """Create tables using raw connection to avoid SQLAlchemy text() issues."""
    sql = SCHEMA_SQL_PG if db_type == "postgresql" else SCHEMA_SQL

    with engine.connect() as conn:
        from sqlalchemy import text
        for statement in sql.split(";"):
            stmt = statement.strip()
            if stmt:
                conn.execute(text(stmt))
        conn.commit()

    logger.info("Database schema initialized")


