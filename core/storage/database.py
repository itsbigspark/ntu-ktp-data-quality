# WRITE — Save pipeline results to database
# ---------------------------------------------------------------------------
def save_results_to_db(
    result: Dict[str, Any],
    config: Dict[str, Any],
    source_file: str = "",
) -> Dict[str, int]:
    """
    Persist pipeline results to the database.
    Creates schema if tables don't exist.
    Returns dict with row counts written: {batch_runs, issues, audit_trail}.
    """
    engine = get_engine(config)
    db_type = config.get("output", {}).get("database", {}).get("engine", "sqlite")

    # Ensure schema exists
    _init_schema_safe(engine, db_type)

    counts = {}

    with engine.connect() as conn:
        from sqlalchemy import text

        # ── 1. batch_runs ──────────────────────────────────────────────────
        scores = result.get("quality_scores", {})
        conn.execute(text("""
            INSERT INTO batch_runs (
                batch_id, timestamp, source_file, rows_processed, columns,
                overall_score, pass, pass_threshold, issues_count,
                llm_calls, data_sent_to_llm,
                completeness, uniqueness, consistency, validity, accuracy, timeliness
            ) VALUES (
                :batch_id, :timestamp, :source_file, :rows_processed, :columns,
                :overall_score, :pass, :pass_threshold, :issues_count,
                :llm_calls, :data_sent_to_llm,
                :completeness, :uniqueness, :consistency, :validity, :accuracy, :timeliness
            )
        """), {
            "batch_id": result["batch_id"],
            "timestamp": result["timestamp"],
            "source_file": source_file,
            "rows_processed": result["rows_processed"],
            "columns": json.dumps(result["columns"]),
            "overall_score": float(result["overall_score"]),
            "pass": bool(result["pass"]),
            "pass_threshold": float(result["pass_threshold"]),
            "issues_count": int(result["issues_count"]),
            "llm_calls": int(result.get("llm_calls", 0)),
            "data_sent_to_llm": bool(result.get("data_sent_to_llm", False)),
            "completeness": float(scores.get("completeness", 0)),
            "uniqueness": float(scores.get("uniqueness", 0)),
            "consistency": float(scores.get("consistency", 0)),
            "validity": float(scores.get("validity", 0)),
            "accuracy": float(scores.get("accuracy", 0)),
            "timeliness": float(scores.get("timeliness", 0)),
        })
        counts["batch_runs"] = 1

        # ── 2. issues — bulk insert via to_sql (100x faster than iterrows) ──
        issues_df = result.get("issues", pd.DataFrame())
        issue_count = 0
        if not isinstance(issues_df, pd.DataFrame):
            issues_df = pd.DataFrame()
        if not issues_df.empty:
            # Normalise column names to what the DB expects
            _col_map = {
                "column": "column_name",
                "issue": "issue_type",
                "detail_technical": "detail",
                "source": "rule",
            }
            bulk = issues_df.rename(columns=_col_map).copy()
            bulk["batch_id"] = result["batch_id"]

            # Ensure required columns exist, truncate long strings
            def _col(df, name, default=""):
                return df[name] if name in df.columns else default

            bulk_rows = pd.DataFrame({
                "batch_id":    bulk["batch_id"],
                "row_id":      pd.to_numeric(_col(bulk, "row_id", 0), errors="coerce").fillna(0).astype(int),
                "column_name": _col(bulk, "column_name", "").astype(str).str[:100],
                "issue_type":  _col(bulk, "issue_type", "").astype(str).str[:100],
                "detail":      _col(bulk, "detail", "").astype(str).str[:500],
                "severity":    _col(bulk, "severity", "").astype(str).str[:50],
                "value":       _col(bulk, "value", "").astype(str).str[:200],
                "expected":    _col(bulk, "expected", "").astype(str).str[:200],
                "rule":        _col(bulk, "rule", "").astype(str).str[:200],
                "suggestion":  _col(bulk, "suggestion", "").astype(str).str[:200],
                "description": _col(bulk, "description", "").astype(str).str[:500],
            })

            # to_sql uses executemany under the hood — single round-trip per chunk
            bulk_rows.to_sql(
                "issues",
                conn,
                if_exists="append",
                index=False,
                chunksize=500,   # 500 rows per INSERT batch
                method="multi",  # single multi-value INSERT statement per chunk
            )
            issue_count = len(bulk_rows)
        counts["issues"] = issue_count

        # ── 3. audit_trail ─────────────────────────────────────────────────
        audit_count = 0
        for step in result.get("audit_trail", []):
            step_name = step.pop("step", "unknown")
            duration = step.pop("duration_ms", 0)
            conn.execute(text("""
                INSERT INTO audit_trail (batch_id, step_name, duration_ms, details)
                VALUES (:batch_id, :step_name, :duration_ms, :details)
            """), {
                "batch_id": result["batch_id"],
                "step_name": step_name,
                "duration_ms": int(duration),
                "details": json.dumps(step),
            })
            # Restore popped keys for other consumers
            step["step"] = step_name
            step["duration_ms"] = duration
            audit_count += 1
        counts["audit_trail"] = audit_count

        conn.commit()

    logger.info(
        f"Database write complete: 1 batch, {counts['issues']} issues, "
        f"{counts['audit_trail']} audit steps"
    )
    return counts


