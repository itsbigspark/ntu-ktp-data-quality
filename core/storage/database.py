"""
core/storage/database.py  --  Database Persistence for the DQ Pipeline
======================================================================
Handles:
  - Creating the schema (batch_runs, issues, quality_scores tables)
  - Writing pipeline results to PostgreSQL or SQLite
  - Querying historical batches and trends

Requires: sqlalchemy (pip install sqlalchemy psycopg2-binary)
For SQLite (local dev): no extra dependencies needed.
"""

