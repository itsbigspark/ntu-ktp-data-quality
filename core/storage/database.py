# WRITE — Save AI enrichment results
# ---------------------------------------------------------------------------
def save_ai_enrichment(
    batch_id: str,
    enrichment_result: Any,
    config: Dict[str, Any],
) -> Dict[str, int]:
    """
    Persist AI enrichment results to the database.

    Args:
        batch_id: The batch this enrichment belongs to.
        enrichment_result: An EnrichmentResult dataclass from ai_enrichment module.
        config: Database configuration dict.

    Returns:
        Dict with counts of rows written per table.
    """
    engine = _get_engine(config)
    db_type = config.get("output", {}).get("database", {}).get("engine", "sqlite")
    _init_schema_safe(engine, db_type)

    counts = {}

    with engine.connect() as conn:
        from sqlalchemy import text

        # -- Smart Rules --
        sr_count = 0
        for rule in (enrichment_result.smart_rules or []):
            if isinstance(rule, dict) and "raw" not in rule:
                conn.execute(text("""
                    INSERT INTO ai_smart_rules
                        (batch_id, column_name, rule_type, description, condition_text, confidence, reasoning)
                    VALUES
                        (:batch_id, :column_name, :rule_type, :description, :condition_text, :confidence, :reasoning)
                """), {
                    "batch_id": batch_id,
                    "column_name": str(rule.get("column", ""))[:100],
                    "rule_type": str(rule.get("rule_type", ""))[:50],
                    "description": str(rule.get("description", ""))[:500],
                    "condition_text": str(rule.get("condition", ""))[:500],
                    "confidence": float(rule.get("confidence", 0)),
                    "reasoning": str(rule.get("reasoning", ""))[:500],
                })
                sr_count += 1
        counts["ai_smart_rules"] = sr_count

        # -- Cross-Column Issues --
        cc_count = 0
        for issue in (enrichment_result.cross_column_issues or []):
            if isinstance(issue, dict):
                cols_involved = issue.get("columns", [])
                if isinstance(cols_involved, str):
                    cols_involved = [cols_involved]
                conn.execute(text("""
                    INSERT INTO ai_cross_column
                        (batch_id, columns_involved, check_type, description, severity, suggested_query)
                    VALUES
                        (:batch_id, :columns_involved, :check_type, :description, :severity, :suggested_query)
                """), {
                    "batch_id": batch_id,
                    "columns_involved": json.dumps(cols_involved),
                    "check_type": str(issue.get("check_type", ""))[:100],
                    "description": str(issue.get("description", ""))[:500],
                    "severity": str(issue.get("severity", "medium"))[:20],
                    "suggested_query": str(issue.get("suggested_query", ""))[:500],
                })
                cc_count += 1
        counts["ai_cross_column"] = cc_count

        # -- Anomaly Explanations --
        ex_count = 0
        for exp in (enrichment_result.explanations or []):
            if isinstance(exp, dict):
                conn.execute(text("""
                    INSERT INTO ai_explanations
                        (batch_id, column_name, issue_type, explanation, business_impact, suggested_action)
                    VALUES
                        (:batch_id, :column_name, :issue_type, :explanation, :business_impact, :suggested_action)
                """), {
                    "batch_id": batch_id,
                    "column_name": str(exp.get("column", ""))[:100],
                    "issue_type": str(exp.get("issue_type", ""))[:100],
                    "explanation": str(exp.get("explanation", ""))[:1000],
                    "business_impact": str(exp.get("business_impact", ""))[:500],
                    "suggested_action": str(exp.get("suggested_action", ""))[:500],
                })
                ex_count += 1
        counts["ai_explanations"] = ex_count

        # -- Issue Triage --
        tr_count = 0
        for item in (enrichment_result.triage or []):
            if isinstance(item, dict):
                conn.execute(text("""
                    INSERT INTO ai_triage
                        (batch_id, priority, column_name, issue_type, issue_count, severity, reason, effort, recommendation)
                    VALUES
                        (:batch_id, :priority, :column_name, :issue_type, :issue_count, :severity, :reason, :effort, :recommendation)
                """), {
                    "batch_id": batch_id,
                    "priority": int(item.get("priority", 99)),
                    "column_name": str(item.get("column", ""))[:100],
                    "issue_type": str(item.get("issue_type", ""))[:100],
                    "issue_count": int(item.get("count", 0)),
                    "severity": str(item.get("severity", "medium"))[:20],
                    "reason": str(item.get("reason", ""))[:500],
                    "effort": str(item.get("effort", ""))[:50],
                    "recommendation": str(item.get("recommendation", ""))[:500],
                })
                tr_count += 1
        counts["ai_triage"] = tr_count

        # -- Executive Summary --
        es_count = 0
        summary_text = enrichment_result.executive_summary or ""
        if summary_text.strip():
            conn.execute(text("""
                INSERT INTO ai_executive_summary
                    (batch_id, summary_text, provider, total_time_secs)
                VALUES
                    (:batch_id, :summary_text, :provider, :total_time_secs)
            """), {
                "batch_id": batch_id,
                "summary_text": summary_text[:5000],
                "provider": str(enrichment_result.provider or ""),
                "total_time_secs": round(enrichment_result.total_time_seconds, 2),
            })
            es_count = 1
        counts["ai_executive_summary"] = es_count

        conn.commit()

    logger.info(
        "AI enrichment saved: %d rules, %d cross-col, %d explanations, %d triage, %d summary",
        counts["ai_smart_rules"], counts["ai_cross_column"],
        counts["ai_explanations"], counts["ai_triage"], counts["ai_executive_summary"],
    )
    return counts


