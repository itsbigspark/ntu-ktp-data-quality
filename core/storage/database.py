def get_recent_batches(
    config: Dict[str, Any],
    limit: int = 20,
) -> pd.DataFrame:
    """Get the most recent batch runs, ordered by timestamp descending."""
    engine = get_engine(config)
    query = f"""
        SELECT batch_id, timestamp, source_file, rows_processed,
               overall_score, pass, issues_count,
               completeness, uniqueness, consistency, validity, accuracy, timeliness
        FROM batch_runs
        ORDER BY timestamp DESC
        LIMIT {limit}
    """
    return pd.read_sql(query, engine)


def get_batch_issues(
    config: Dict[str, Any],
    batch_id: str,
) -> pd.DataFrame:
    """Get all issues for a specific batch."""
    engine = get_engine(config)
    from sqlalchemy import text
    query = text("""
        SELECT row_id, column_name, issue_type, detail, severity,
               value, expected, suggestion, description
        FROM issues
        WHERE batch_id = :batch_id
        ORDER BY row_id, column_name
    """)
    return pd.read_sql(query, engine, params={"batch_id": batch_id})


def get_score_trend(
    config: Dict[str, Any],
    limit: int = 50,
) -> pd.DataFrame:
    """Get quality score trend over time."""
    engine = get_engine(config)
    query = f"""
        SELECT batch_id, timestamp, overall_score, pass,
               completeness, uniqueness, consistency, validity, accuracy, timeliness
        FROM batch_runs
        ORDER BY timestamp DESC
        LIMIT {limit}
    """
    df = pd.read_sql(query, engine)
    return df.sort_values("timestamp")  # chronological order


def get_batch_audit(
    config: Dict[str, Any],
    batch_id: str,
) -> pd.DataFrame:
    """Get audit trail for a specific batch."""
    engine = get_engine(config)
    from sqlalchemy import text
    query = text("""
        SELECT step_name, duration_ms, details, created_at
        FROM audit_trail
        WHERE batch_id = :batch_id
        ORDER BY id
    """)
    return pd.read_sql(query, engine, params={"batch_id": batch_id})


