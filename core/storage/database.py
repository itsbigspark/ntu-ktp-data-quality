# ---------------------------------------------------------------------------
# Connection management
# ---------------------------------------------------------------------------
def _get_engine(config: Dict[str, Any]):
    """Create a SQLAlchemy engine from config dict."""
    from sqlalchemy import create_engine

    db_cfg = config.get("output", {}).get("database", {})
    engine_type = db_cfg.get("engine", "sqlite")

    if engine_type == "sqlite":
        db_path = db_cfg.get("path", "./output/dq_investigator.db")
        os.makedirs(os.path.dirname(os.path.abspath(db_path)), exist_ok=True)
        url = f"sqlite:///{db_path}"
        logger.info(f"Using SQLite: {db_path}")
    elif engine_type == "postgresql":
        host = db_cfg.get("host", "localhost")
        port = db_cfg.get("port", 5432)
        name = db_cfg.get("name", "dq_investigator")
        user = db_cfg.get("user", "")
        password = db_cfg.get("password", "")
        url = f"postgresql://{user}:{password}@{host}:{port}/{name}"
        logger.info(f"Using PostgreSQL: {host}:{port}/{name}")
    else:
        raise ValueError(f"Unsupported database engine: {engine_type}")

    if url not in _ENGINE_CACHE:
        kwargs = {"pool_pre_ping": True} if engine_type == "postgresql" else {}
        _ENGINE_CACHE[url] = create_engine(url, **kwargs)
    return _ENGINE_CACHE[url]


# ---------------------------------------------------------------------------
# Schema creation
# ---------------------------------------------------------------------------
def init_schema(config: Dict[str, Any]) -> None:
    """Create tables if they don't exist."""
    engine = get_engine(config)
    db_type = config.get("output", {}).get("database", {}).get("engine", "sqlite")

    sql = SCHEMA_SQL_PG if db_type == "postgresql" else SCHEMA_SQL

    with engine.connect() as conn:
        for statement in sql.split(";"):
            stmt = statement.strip()
            if stmt:
                conn.execute(conn.connection.cursor().execute(stmt) if False else __import__("sqlalchemy").text(stmt))
        conn.commit()

    logger.info("Database schema initialized")


def _init_schema_safe(engine, db_type: str = None) -> None:
    """Create tables using raw connection to avoid SQLAlchemy text() issues."""
    # Always detect from the actual engine URL — never trust the caller's config dict
    # which may say "sqlite" even when DATABASE_URL points to PostgreSQL.
    _engine_url = str(engine.url)
    _is_pg = "postgresql" in _engine_url or "postgres" in _engine_url
    sql = SCHEMA_SQL_PG if _is_pg else SCHEMA_SQL

    with engine.connect() as conn:
        from sqlalchemy import text
        for statement in sql.split(";"):
            stmt = statement.strip()
            if stmt:
                conn.execute(text(stmt))
        conn.commit()

    logger.info("Database schema initialized")


